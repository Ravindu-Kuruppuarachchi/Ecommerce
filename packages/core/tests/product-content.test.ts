import assert from 'node:assert/strict';
import { reconcileVariantRows } from '../src/commerce';
import { parseDescription } from '../src/description';
const before = [{ name: 'Species', values: ['Platy', 'Gourami'] }];
const rows = [{ id:'a', optionValues:{Species:'Platy'}, price:'130', quantity:'10' }, { id:'b', optionValues:{Species:'Gourami'}, price:'150', quantity:'20' }];
const fresh = (optionValues: Record<string,string>) => ({ id: '', optionValues, price: '', quantity: '0' });
const renamed = reconcileVariantRows(before, [{name:'Fish type',values:['Platy','Gourami']}], rows, fresh);
assert.equal(renamed[0].id,'a');
assert.equal(renamed[0].quantity,'10');
assert.deepEqual(renamed[0].optionValues,{'Fish type':'Platy'});
const added = reconcileVariantRows(before,[{name:'Species',values:['Platy','Gourami','Tetra']}],rows,fresh);
assert.equal(added[1].id,'b'); assert.equal(added[2].quantity,'0');
const expanded = reconcileVariantRows(before,[...before,{name:'Size',values:['S','L']}],rows,fresh);
assert.equal(expanded.length,4); assert.ok(expanded.every(row=>!row.id && row.quantity==='0'));
assert.deepEqual(reconcileVariantRows(before,[],rows,fresh),[]);
const blocks = parseDescription('## Care\nKeep warm.\n\n| Detail | Value |\n| --- | --- |\n| Size | Small |\n\n- Food\n- Water\n\n1. First\n2. Second');
assert.deepEqual(blocks.map(block=>block.kind),['heading','paragraph','table','list','list']);
assert.equal(parseDescription('<script>alert(1)</script>')[0].kind,'paragraph');
assert.deepEqual(parseDescription('Old text\nsecond line'),[{kind:'paragraph',text:'Old text\nsecond line'}]);
console.log('Variant identity, stock preservation and description formatting checks passed.');
